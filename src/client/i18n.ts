export type Lang = "en" | "es" | "fr" | "pt";

export const LANGUAGES: { code: Lang; name: string }[] = [
  { code: "en", name: "English" },
  { code: "es", name: "Español" },
  { code: "fr", name: "Français" },
  { code: "pt", name: "Português" },
];

const DICTS: Record<Lang, Dict> = { en, es, fr, pt };
const KEY = "routine-chat.lang.v1";

export function getLang(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    if (v && v in DICTS) return v as Lang;
  } catch { /* storage unavailable */ }
  return "en";
}

let current: Lang = getLang();
document.documentElement.lang = current;

/** Changes the UI language and notifies listeners (the app re-mounts on "langchange"). */
export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try { localStorage.setItem(KEY, lang); } catch { /* storage unavailable */ }
  document.documentElement.lang = lang;
  window.dispatchEvent(new Event("langchange"));
}

/** Translates a key, replacing {placeholders} with the given values. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[current][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

